// Generates the browser-ready rendering engine in public/engine.
// The dashboard renderer is plain, dependency-free ESM, so the same modules
// used by the Express server can run in the browser after copying them with
// their relative import structure preserved.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'public', 'engine');

function copyDir(srcDir, outDir, filter) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const srcPath = path.join(srcDir, entry.name);
    const outPath = path.join(outDir, entry.name);
    if (entry.isDirectory()) {
      copyDir(srcPath, outPath, filter);
    } else if (!filter || filter(entry.name)) {
      fs.copyFileSync(srcPath, outPath);
    }
  }
}

fs.rmSync(OUT, { recursive: true, force: true });

copyDir(path.join(SRC, 'themes'), path.join(OUT, 'themes'), (name) => name.endsWith('.theme.js'));
copyDir(
  path.join(SRC, 'utils'),
  path.join(OUT, 'utils'),
  (name) => ['svg-sanitizer.js', 'svg-accessibility.js', 'theme-accessibility.js'].includes(name)
);
copyDir(
  path.join(SRC, 'renderers'),
  path.join(OUT, 'renderers'),
  (name) => ['svg.renderer.js', 'chart.renderer.js', 'cp-section.renderer.js', 'dashboard.renderer.js'].includes(name)
);
copyDir(path.join(SRC, 'data'), path.join(OUT, 'data'), (name) => name === 'demo-profile.js');
fs.copyFileSync(path.join(SRC, 'constants.js'), path.join(OUT, 'constants.js'));

const indexPath = path.join(OUT, 'index.js');
fs.writeFileSync(
  indexPath,
  `// Generated by scripts/build-engine.js — do not edit directly.
export { setTheme, getTheme, SUPPORTED_THEME_NAMES, wrapSvg } from './renderers/svg.renderer.js';
export {
  renderDashboard,
  renderDashboardSvg,
  buildDemoModel,
  normalizeSections,
  normalizeStyle,
  DASHBOARD_SECTIONS,
  DEFAULT_SECTIONS,
  STYLE_NAMES,
} from './renderers/dashboard.renderer.js';
export { DEMO_PROFILE } from './data/demo-profile.js';
`
);

console.log('Built browser engine in public/engine');

// Keep the browser module graph cache-safe on static hosting: append a build id
// to every relative import so a new deploy is never served from a stale cache.
const BUILD_ID = process.env.GM_BUILD_ID || Date.now().toString(36);

function versionImports(file) {
  const code = fs.readFileSync(file, 'utf8');
  const next = code.replace(/(from\s+['"])(\.\.?\/[^'"]+\.js)(['"])/g, `$1$2?v=${BUILD_ID}$3`);
  if (next !== code) fs.writeFileSync(file, next);
}

function walkJs(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const target = path.join(dir, entry.name);
    if (entry.isDirectory()) walkJs(target);
    else if (entry.name.endsWith('.js')) versionImports(target);
  }
}

walkJs(OUT);
